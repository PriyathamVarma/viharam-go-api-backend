	// Supabase PostgreSQL is authoritative whenever it is configured. MongoDB
	// remains only as a temporary local compatibility mode when PostgreSQL is
	// absent, so production cannot accidentally split API traffic between stores.
	if mongoDB != nil && db == nil {
		authRepo = auth.NewMongoRepository(mongoDB)
	} else {
		authRepo = auth.NewRepository(db)
	}
